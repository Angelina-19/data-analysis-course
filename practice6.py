# Відповідь: 
# - std (стандартне відхилення) — це квадратний корінь із дисперсії, що показує, 
#   наскільки в середньому значення відхиляються від середнього арифметичного.
# - 25% (Q1, перший квартиль) та 75% (Q3, третій квартиль) визначають міру#   розкиду на основі інтерквартильного розмаху (IQR = Q3 - Q1), який охоплює центральні 50% даних.
# - min та max визначають абсолютний розмах (Range = max - min), тобто ширину всього діапазону даних.

# ПИТАННЯ 2: Чи розумієте, чому заповнення пропуску середнім штучно зменшує std, і чи можете показати механіку цього на конкретних числах?
# Відповідь: 
# Заповнення пропусків значенням середнього (mean) додає до набору даних нову точку, 
# яка ідеально збігається із центром розподілу (відхилення від середнього дорівнює 0). 
# Оскільки чисельник у формулі дисперсії (сума квадратів відхилень) не змінюється, 
# а знаменник (кількість елементів n) збільшується на 1, загальне значення дисперсії та std зменшується.
# Наприклад: є ряд [70, 80], mean = 75, std ≈ 7.07. Якщо додати пропуск, заповнений середнім [70, 80, 75], 
# то нове mean = 75, а новий std стане близько 5.0 (розкид зменшився через штучну концентрацію біля центру).

# ПИТАННЯ 3: Чи можете пояснити, чому порівнювати абсолютні значення std двох груп чи регіонів різного масштабу без коефіцієнта варіації може привести до хибного висновку?
# Відповідь: 
# Абсолютне стандартне відхилення (std) залежить від абсолютного масштабу (одиниць вимірювання та середнього рівня) даних. 
# Наприклад, std = 5 для групи із середнім значенням 10 означає величезну мінливість (50%), 
# тоді як std = 5 для групи із середнім значенням 1000 — це мізерна мінливість (0.5%). 
# Тому для коректного порівняння використовується коефіцієнт варіації (CV), очищений від масштабу.

