import numpy as np
import matplotlib.pyplot as plt

# ==========================================
# ПРАКТИЧНА РОБОТА №21 (ВАРІАНТ 1)
# ==========================================

np.random.seed(1)
exact_value = np.pi / 4  
print(f"--- ТОЧНЕ ЗНАЧЕННЯ ДЛЯ ВАРІАНТУ 1 ---")
print(f"Точне аналітичне значення: {exact_value:.4f}\n")



print("--- ЗАВДАННЯ 1: Оцінка при N = 1000 ---")
N_task1 = 1000
x_t1 = np.random.uniform(0, 1, size=N_task1)
y_t1 = np.random.uniform(0, 1, size=N_task1)


inside_circle = (x_t1**2 + y_t1**2) <= 1
mc_estimate_t1 = inside_circle.mean() * 1.0  

print(f"Оцінка площі методом Монте-Карло (N={N_task1}): {mc_estimate_t1:.4f}\n")



print("--- ЗАВДАННЯ 2: Порівняння з точним значенням ---")
absolute_error = abs(mc_estimate_t1 - exact_value)
relative_error_percent = (absolute_error / exact_value) * 100

print(f"Абсолютна похибка: {absolute_error:.4f}")
print(f"Відносна похибка: {relative_error_percent:.2f}%\n")



print("--- ЗАВДАННЯ 3: Збіжність за N (середня похибка за 200 повторень) ---")
N_values = [100, 1_000, 10_000, 100_000]
mean_errors = []


np.random.seed(1)

for N in N_values:
    errors = []
    for _ in range(200):
        x = np.random.uniform(0, 1, size=N)
        y = np.random.uniform(0, 1, size=N)
        estimate = ((x**2 + y**2) <= 1).mean() * 1.0
        errors.append(abs(estimate - exact_value))
    
    mean_err = np.mean(errors)
    mean_errors.append(mean_err)
    print(f"N = {N:6d} | Середня абсолютна похибка = {mean_err:.5f}")

print()



print("--- ЗАВДАННЯ 4: Побудова графіка залежності похибки від N ---")

plt.figure(figsize=(8, 5))
plt.plot(N_values, mean_errors, marker='o', linestyle='-', color='b', linewidth=2, label='Середня абсолютна похибка')
plt.xscale('log')
plt.yscale('log')
plt.xlabel('Кількість випробувань N (логарифмічний масштаб)', fontsize=12)
plt.ylabel('Середня абсолютна похибка', fontsize=12)
plt.title('Збіжність методу Монте-Карло (Варіант 1, Київ)', fontsize=14)
plt.grid(True, which="both", ls="--")
plt.legend()
plt.show()
print("Графік успішно побудовано!")


