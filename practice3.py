# Питання 1: Чи можете пояснити, чому стовпець "місто" — номінальна шкала, а стовпець "хмарність" — шкала відношень?
# Відповідь: Стовпець "місто" є номінальною шкалою, оскільки його значення є якісними категоріями (назвами об'єктів), між якими неможливо встановити математичний порядок чи ієрархію. 
# Стовпець "хмарність" є шкалою відношень, оскільки він має фіксований абсолютний нуль (0% означає повну відсутність хмарності), а значення можна коректно порівнювати не лише за різницею, а й через кратність (наприклад, 80% хмарності вдвічі більше за 40%).

# Питання 2: Чи розумієте, чому вихідна wide-таблиця з місяцями в стовпцях не вважається tidy, і що саме змінюється в її структурі після melt()?
# Відповідь: Вихідна wide-таблиця не є tidy, оскільки назви місяців виступають окремими стовпцями, хоча насправді вони є значеннями однієї ознаки ("місяць"), а значення хмарності "розмазані" по рядку. 
# Після melt() структура змінюється: кожен місяць стає окремим рядком, формуючи три чіткі колонки правила tidy data: "Місто", "місяць" і "хмарність".

# Питання 3: Чи можете описати, чим формат CSV принципово відрізняється від JSON при зберіганні однієї й тієї самої таблиці?
# Відповідь: CSV зберігає дані у вигляді плоского тексту, де рядки відокремлені переносів рядків, а стовпці — комами (таблична структура без метаданих типів).# JSON зберігає дані як структурований текст у вигляді масиву об'єктів (словників) із явними ключами для кожної змінної, що робить його ідеальним для ієрархічних даних та передачі через web API.