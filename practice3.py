print("=== ЗАВДАННЯ 1: Побудова wide-таблиці свого варіанта ===")
wide = pd.DataFrame({
    "Місто": ["Київ"],
    "Січ": [78], "Лют": [74], "Бер": [68], "Кві": [58],
    "Тра": [50], "Чер": [44], "Лип": [40], "Сер": [42],
    "Вер": [52], "Жов": [66], "Лис": [76], "Гру": [82]
})
print(wide)
print("\n" + "="*50 + "\n")


print("=== ЗАВДАННЯ 2: Приведення до tidy (melt) ===")
tidy = wide.melt(id_vars="Місто", var_name="місяць", value_name="хмарність")
print(tidy)
print("\nФорма (shape) tidy-таблиці:", tidy.shape)
print("Пояснення: У вихідній wide-таблиці був 1 рядок і 13 стовпців. Метод melt() розгорнув 12 стовпців місяців у рядки, утворивши 12 рядків і 3 стовпці.")
print("\n" + "="*50 + "\n")


print("=== ЗАВДАННЯ 3: Класифікація змінних ===")
print("1. 'Місто' — Номінальна шкала (категоріальна без порядку, об'єкти лише ідентифікуються назвами).")
print("2. 'місяць' — Порядкова шкала (назви/періоди місяців мають чітку хронологічну послідовність).")
print("3. 'хмарність' — Шкала відношень (наявний абсолютний нуль: 0% означає повну відсутність хмарності, можливе порівняння через відношення).")
print("\n" + "="*50 + "\n")


print("=== ЗАВДАННЯ 4: Зворотне перетворення й перевірка ===")
back_wide = tidy.pivot(index="Місто", columns="місяць", values="хмарність").reset_index()
month_order = ["Місто", "Січ", "Лют", "Бер", "Кві", "Тра", "Чер", "Лип", "Сер", "Вер", "Жов", "Лис", "Гру"]
back_wide = back_wide[month_order]
print(back_wide)
print("Перевірка: Значення повністю збігаються з оригінальною таблицею з Завдання 1.")
print("\n" + "="*50 + "\n")


print("=== ЗАВДАННЯ 5: Читання й запис (CSV та JSON) ===")
tidy.to_csv("variant.csv", index=False)
tidy.to_json("variant.json", orient="records", force_ascii=False)

reloaded_csv = pd.read_csv("variant.csv")
reloaded_json = pd.read_json("variant.json")

print("CSV прочитано успішно. Форма:", reloaded_csv.shape)
print("JSON прочитано успішно. Форма:", reloaded_json.shape)

print("\n--- Зміст variant.csv ---")
print(open("variant.csv", "r", encoding="utf-8").read())

print("--- Зміст variant.json ---")
print(open("variant.json", "r", encoding="utf-8").read())


