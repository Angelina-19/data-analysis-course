import numpy as np
from scipy import stats

print("=== ВИКОНАННЯ ПРАКТИЧНОЇ РОБОТИ №14 (ВАРІАНТ 1: КИЇВ) ===")


kyiv_humidity = np.array([84, 82, 78, 70, 65, 63, 61, 63, 68, 75, 81, 85])
norm_value = 74


print("\n--- ЗАВДАННЯ 1: Одновибірковий t-критерій ---")
t_stat_1, p_value_1 = stats.ttest_1samp(kyiv_humidity, popmean=norm_value)
print(f"t-статистика: {t_stat_1:.4f}")
print(f"p-value: {p_value_1:.4f}")

alpha = 0.05
if p_value_1 < alpha:
    print("Висновок: Відхиляємо H0 (середня вологість статистично значуще відрізняється від норми).")
else:
    print("Висновок: Немає підстав відхиляти H0 (різниця з нормою статистично не значуща).")



print("\n--- ЗАВДАННЯ 2: Ручна перевірка t-статистики ---")
n = len(kyiv_humidity)
mean_val = kyiv_humidity.mean()
std_val = kyiv_humidity.std(ddof=1)
manual_t_stat = (mean_val - norm_value) / (std_val / np.sqrt(n))

print(f"Середнє значення (x̄): {mean_val:.4f}")
print(f"Стандартне відхилення (s): {std_val:.4f}")
print(f"Обчислена вручну t-статистика: {manual_t_stat:.4f}")
print(f"Збігається з ttest_1samp: {np.isclose(manual_t_stat, t_stat_1)}")



print("\n--- ЗАВДАННЯ 3: Двовибірковий незалежний критерій (Одеса) ---")
odesa_humidity = np.array([82, 80, 78, 74, 71, 69, 67, 68, 72, 76, 80, 83])

stat_lev_3, p_lev_3 = stats.levene(kyiv_humidity, odesa_humidity)
print(f"Levene stat: {stat_lev_3:.4f}, p_value: {p_lev_3:.4f}")

if p_lev_3 < 0.05:
    equal_variance_3 = False
    print("Дисперсії різні -> використовуємо Welch-варіант (equal_var=False)")
else:
    equal_variance_3 = True
    print("Дисперсії рівні -> використовуємо стандартний варіант (equal_var=True)")

t_stat_3, p_value_3 = stats.ttest_ind(kyiv_humidity, odesa_humidity, equal_var=equal_variance_3)
print(f"t_stat: {t_stat_3:.4f}, p_value: {p_value_3:.4f}")



print("\n--- ЗАВДАННЯ 4: Зміна висновку Лівена (Харків) ---")
kharkiv_humidity = np.array([83, 80, 75, 68, 62, 60, 58, 60, 66, 73, 79, 84])

stat_lev_4, p_lev_4 = stats.levene(kyiv_humidity, kharkiv_humidity)
print(f"Levene stat: {stat_lev_4:.4f}, p_value: {p_lev_4:.4f}")

if p_lev_4 < 0.05:
    equal_variance_4 = False
    print("Дисперсії різні -> використовуємо Welch-варіант (equal_var=False)")
else:
    equal_variance_4 = True
    print("Дисперсії рівні -> використовуємо стандартний варіант (equal_var=True)")

t_stat_4, p_value_4 = stats.ttest_ind(kyiv_humidity, kharkiv_humidity, equal_var=equal_variance_4)
print(f"t_stat: {t_stat_4:.4f}, p_value: {p_value_4:.4f}")



print("\n--- ЗАВДАННЯ 5: Парний t-критерій (Ранок vs Вечір) ---")
amplitude = np.array([5, 6, 8, 12, 16, 18, 19, 17, 13, 9, 6, 5])
kyiv_evening = kyiv_humidity - amplitude

t_stat_5, p_value_5 = stats.ttest_rel(kyiv_humidity, kyiv_evening)

print(f"Ранкові значення: {kyiv_humidity}")
print(f"Вечірні значення: {kyiv_evening}")
print(f"t-статистика (парний): {t_stat_5:.4f}")
print(f"p-value: {p_value_5:.10f}")
print("Висновок: Різниця між ранковою та вечірньою вологістю статистично високозначуща.")




