import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.stats import pearsonr, spearmanr

print("=== ПРАКТИЧНА РОБОТА №16 (Варіант 1 - Київ) ===")


np.random.seed(1)
city = "Київ"
monthly_temp = [-4, -3, 2, 9, 15, 19, 21, 20, 14, 8, 2, -2]

months = ["Січ", "Лют", "Бер", "Кві", "Тра", "Чер",
          "Лип", "Сер", "Вер", "Жов", "Лис", "Гру"]

rows = []
for month, temp in zip(months, monthly_temp):
    heating_days = np.clip(18 - temp + np.random.normal(0, 1.5), 0, 30)
    heating_days = round(heating_days)
    cost = 0.15 * heating_days + np.random.normal(0, 1.0)
    cost = round(max(cost, 0), 1)
    rows.append({
        "місто": city, "місяць": month, "температура": temp,
        "опалювальні_дні": heating_days, "витрати_на_палення": cost,
    })

climate = pd.DataFrame(rows)
print("\n[Вихідний DataFrame climate]:")
print(climate)


print("\n--- ЗАВДАННЯ 1: Побудова діаграми розсіювання ---")
fig, ax = plt.subplots(figsize=(8, 5))
ax.scatter(climate["температура"], climate["витрати_на_палення"], color='crimson', s=70, zorder=3)
ax.set_xlabel("Середньомісячна температура, °C")
ax.set_ylabel("Витрати на опалення, умовні тис. грн")
ax.set_title("Залежність витрат на опалення від температури повітря (Київ)")
ax.grid(True, linestyle='--', alpha=0.6)
plt.show()
print("Аналіз хмари точок: Зв'язок лінійний і негативний (обернений) — чим вища температура, тим менші витрати.")



print("\n--- ЗАВДАННЯ 2: Обчислення коефіцієнтів кореляції та довірчого інтервалу ---")
temp = climate["температура"]
cost = climate["витрати_на_палення"]

r = pearsonr(temp, cost)
rho = spearmanr(temp, cost)
ci = r.confidence_interval(confidence_level=0.95)

print(f"Пірсон: r = {r.statistic:.3f}, p-value = {r.pvalue:.2e}")
print(f"Спірмен: rho = {rho.statistic:.3f}, p-value = {rho.pvalue:.2e}")
print(f"95% довірчий інтервал для Пірсона: [{ci.low:.3f}, {ci.high:.3f}]")
print("Висновок: p-value < 0.05, тому гіпотеза H0 відхиляється. Зв'язок статистично значущий.")



print("\n--- ЗАВДАННЯ 3: Кор. матриця для трьох змінних ---")
df_3 = climate[["температура", "опалювальні_дні", "витрати_на_палення"]]

print("Матриця (Пірсон):")
print(df_3.corr(method="pearson"))

print("\nМатриця (Спірмен):")
print(df_3.corr(method="spearman"))
print("Висновок: Найсильніша пара — температура й опалювальні дні. При переході на Спірмен висновки зберігаються.")



print("\n--- ЗАВДАННЯ 4: Кореляція та причинність ---")
print("Коментар: У цьому наборі зв'язок прямий і детермінований формулою генерації (температура впливає на дні, дні на витрати).")
print("Це справжній причиново-наслідковий зв'язок, а не побічний конфаундер чи збіг.")



print("\n--- ЗАВДАННЯ 5: Перевірка стійкості до викидів ---")
climate_outlier = climate.copy()

climate_outlier.loc[11, "витрати_на_палення"] *= 5

r_out = pearsonr(climate_outlier["температура"], climate_outlier["витрати_на_палення"])
rho_out = spearmanr(climate_outlier["температура"], climate_outlier["витрати_на_палення"])

print(f"З викидом Пірсон: r = {r_out.statistic:.3f}, p = {r_out.pvalue:.2e}")
print(f"З викидом Спірмен: rho = {rho_out.statistic:.3f}, p = {rho_out.pvalue:.2e}")
print("Висновок: Пірсон сильно змінився (чутливий до викидів), Спірмен залишився стійким через використання рангів.")


