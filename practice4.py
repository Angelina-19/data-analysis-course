import numpy as np
import pandas as pd

print("=== ПРАКТИЧНА РОБОТА №4 (Варіант 1: Київ) ===")


# ==========================================
# ЗАВДАННЯ 1: Побудова брудного набору даних
# ==========================================
print("--- ЗАВДАННЯ 1: Побудова брудного набору даних ---")


orders_dirty = pd.DataFrame([
    {"id": 1, "товар": "Смарт-годинник", "місто": "Київ", "ціна": "850 грн", "кількість": 3},
    {"id": 2, "товар": "Смарт-годинник", "місто": "  Київ  ", "ціна": "850 грн", "кількість": np.nan},  
    {"id": 3, "товар": "Смарт-годинник", "місто": "КИЇВ", "ціна": "850 грн", "кількість": 3},      
    {"id": 3, "товар": "Смарт-годинник", "місто": "КИЇВ", "ціна": "850 грн", "кількість": 3},       
    {"id": 4, "товар": "Смарт-годинник", "місто": "Київ", "ціна": 850.0, "кількість": np.nan},        
    {"id": 5, "товар": "Смарт-годинник", "місто": "Київ", "ціна": 850.0, "кількість": 2},
    {"id": 6, "товар": "Смарт-годинник", "місто": "Київ", "ціна": 850.0, "кількість": 4},
    {"id": 7, "товар": "Смарт-годинник", "місто": "Київ", "ціна": "8500 грн", "кількість": 1},      
])

print("Початковий брудний DataFrame:")
print(orders_dirty)
print("\n" + "="*60 + "\n")


# ==========================================
# ЗАВДАННЯ 4 (Попередній етап): Типи даних і узгодження категорій
# ==========================================
print("--- ЗАВДАННЯ 4: Типи даних і узгодження категорій ---")


orders_dirty["ціна"] = (
    orders_dirty["ціна"]
    .astype(str)
    .str.replace(" грн", "", regex=False)
    .astype(float)
)


orders_dirty["місто"] = orders_dirty["місто"].str.strip().str.lower()

print("Унікальні міста після узгодження категорій (.unique()):")
print(orders_dirty["місто"].unique())
print("\nDataFrame після приведення типів і категорій:")
print(orders_dirty)
print("\n" + "="*60 + "\n")


# ==========================================
# ЗАВДАННЯ 2: Пропуски
# ==========================================
print("--- ЗАВДАННЯ 2: Обробка пропусків ---")


print("Кількість пропусків по стовпцях:")
print(orders_dirty.isna().sum())


median_qty = orders_dirty["кількість"].median()
print(f"\nМедіана кількості: {median_qty}")

orders_dirty["кількість"].fillna(median_qty, inplace=True)
print("\nDataFrame після заповнення пропусків у стовпці 'кількість':")
print(orders_dirty)
print("\n" + "="*60 + "\n")


# ==========================================
# ЗАВДАННЯ 3: Дублікати
# ==========================================
print("--- ЗАВДАННЯ 3: Пошук та видалення дублікатів ---")


print("Кількість повних дублікатів рядків (без subset):", orders_dirty.duplicated().sum())


print("Кількість дублікатів за id (subset=['id']):", orders_dirty.duplicated(subset=["id"]).sum())
orders_dirty.drop_duplicates(subset=["id"], inplace=True)

print(f"\nКількість рядків після видалення дублікатів: {len(orders_dirty)}")
print(orders_dirty)
print("\n" + "="*60 + "\n")


# ==========================================
# ЗАВДАННЯ 5: Викиди
# ==========================================
print("--- ЗАВДАННЯ 5: Аналіз викидів за методом IQR ---")


q1, q3 = orders_dirty["ціна"].quantile([0.25, 0.75])
iqr = q3 - q1
lower_bound = q1 - 1.5 * iqr
upper_bound = q3 + 1.5 * iqr

print(f"Q1 = {q1}, Q3 = {q3}, IQR = {iqr}")
print(f"Нижня межа = {lower_bound}, Верхня межа = {upper_bound}")


outliers = orders_dirty[(orders_dirty["ціна"] < lower_bound) | (orders_dirty["ціна"] > upper_bound)]
print("\nЗнайдені викиди:")
print(outliers)


