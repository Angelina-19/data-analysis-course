import numpy as np
from scipy import stats
import matplotlib.pyplot as plt

print("=== ПРАКТИЧНА РОБОТА. ВАРІАНТ 1 (КИЇВ) ===")
print("Средовище: macOS / Python\n")


np.random.seed(1)
daily_temps = np.random.normal(loc=21, scale=2.5, size=30)

print("--- Завдання 1 ---")
print("Вибірка денних температур (daily_temps):")
print(daily_temps)
print(f"Середнє вибірки (.mean()): {daily_temps.mean():.4f}")
print(f"Стандартне відхилення вибірки (.std()): {daily_temps.std():.4f}\n")



mean, std = daily_temps.mean(), daily_temps.std()
dist = stats.norm(loc=mean, scale=std)

print("--- Завдання 2 ---")
print(f"Підібрані параметри нормального розподілу:")
print(f"mu (loc) = {mean:.4f}")
print(f"sigma (scale) = {std:.4f}\n")


print("--- Завдання 3 ---")
print("Побудова графіка гістограми та теоретичної PDF-кривої...")

x = np.linspace(daily_temps.min() - 5, daily_temps.max() + 5, 200)

plt.figure(figsize=(9, 5))
plt.hist(daily_temps, bins=7, density=True, edgecolor="white", alpha=0.7, color="skyblue", label="Гістограма вибірки")
plt.plot(x, dist.pdf(x), color="crimson", linewidth=2.5, label="Теоретична PDF крива")
plt.title("Розподіл денних температур у Києві (Липень)", fontsize=12)
plt.xlabel("Температура (°C)", fontsize=10)
plt.ylabel("Густина ймовірності", fontsize=10)
plt.legend()
plt.grid(True, linestyle="--", alpha=0.5)
plt.show()

print("Оцінка на око: Крива проходить близько до верхівок стовпців гістограми, повторюючи дзвіноподібну форму.\n")


lower_bound = mean - std
upper_bound = mean + std
p_within_1std = dist.cdf(upper_bound) - dist.cdf(lower_bound)

print("--- Завдання 4 ---")
print(f"Інтервал [mean - std, mean + std]: [{lower_bound:.2f}, {upper_bound:.2f}] °C")
print(f"Ймовірність потрапляння в інтервал (CDF): {p_within_1std:.4f} або {p_within_1std * 100:.2f}%")
print("Пояснення: Отримане значення (~68.27%) ідеально відповідає правилу 68-95-99.7 (правилу трьох сигм).\n")


p95_cutoff = dist.ppf(0.95)

print("--- Завдання 5 ---")
print(f"Температура для 95-го процентилю (95% cutoff): {p95_cutoff:.2f} °C")
print("Пояснення: 95% усіх денних температур лежать нижче або дорівнюють цьому значенню, а на спекотніші 5% припадають температури вище.\n")


