# Питання 1: Чи можете пояснити різницю між тим, що повертає .pdf(x), і тим, 
# що повертає .cdf(x) — на яке питання відповідає кожна з цих функцій?
# --------------------------------------------------------------------------
# Відповідь:
# - .pdf(x) (Probability Density Function) повертає густину ймовірності в конкретній точці x. 
#   Вона відповідає на запитання: "Наскільки щільно значеня зосереджені поблизу даної точки x?" 
#   (це не ймовірність конкретної точки, а густина).
# - .cdf(x) (Cumulative Distribution Function) повертає накопичену ймовірність того, що 
#   випадкова величина набуде значення, меншого або рівного x. 
#   Вона відповідає на запитання: "Яка частка спостережень лежить нижче заданого значення x?"


# Питання 2: Чи можете пояснити, чому значення .pdf(x) може бути числом більшим за 1, 
# і чому це не помилка й не суперечить тому, що ймовірність не перевищує 1?
# --------------------------------------------------------------------------
# Відповідь:
# - .pdf(x) — це густина ймовірності, а не самій вимір ймовірності (ймовірність потрапляння в одну конкретну точку для неперервної величини взагалі дорівнює нулю). 
# - Значення густини може перевищувати 1 (наприклад, якщо крива дуже висока і вузька). 
# - Головна умова для PDF — інтеграл (повна площа під усім графіком кривої) дорівнює рівно 1, 
#   а не висота в окремій точці.


# Питання 3: Чи розумієте, чому .ppf() називають оберненою до .cdf() функцією — 
# що на вхід і що на вихід дає кожна з них?
# --------------------------------------------------------------------------
# Відповідь:
# - .ppf(q) (Percent Point Function) є математично оберненою функцією до .cdf(x).
# - .cdf(x): на вхід приймає значення величини (наприклад, температуру), а на вихід дає 
#   накопичену ймовірність (частку від 0 до 1).
# - .ppf(q): на вхід приймає накопичену ймовірність або квантиль q (наприклад, 0.95), а на вихід 
#   дає порогове значення величини (температуру), нижче якої лежить ця частка спостережень.