"""
Питання 1: Чи можете пояснити, чому .loc[1:6] і .iloc[0:6] можуть повернути різну кількість рядків, залежно від того, який саме індекс у таблиці?
Відповідь: 
Метод .loc працює за мітками (labels) індексу і є включним з обох боків. Якщо індекс кастомний або змінений, 
діапазон шукатиме мітки від 1 до 6 включно. Натомість .iloc працює за порядковими позиціями (від 0), і права межа 
там не включається (як звичайний зріз у Python). Якщо індекс не починається з 0 або має пропуски, .loc та .iloc дадуть 
різні результати або помилку.

Питання 2: Чи розумієте, чому df["avg_temp"] > 10 and df["precip"] > 50 викличе помилку, а (df["avg_temp"] > 10) & (df["precip"] > 50) — ні?
Відповідь:Оператор 'and' намагається оцінити весь об'єкт Series як єдине ціле (True/False), що викликає неоднозначність для цілої колонки.
Символ '&' перевантажений у pandas для поелементного (векторизованого) логічного множення рядків, а круглі дужки 
обов'язкові через високий пріоритет оператора '&' порівняно з операторами порівняння (>).

Питання 3: Чи можете описати словами, у чому різниця між обчислюваним стовпцем, створеним формулою, і створеним через .apply()?
Відповідь:
Формула (векторизована операція) виконується дуже швидко на рівні C (NumPy) одразу для всієї колонки без циклів.
Метод .apply() застосовує функцію поелементно (рядком), що фактично є циклом усередині та працює повільніше, проте 
необхідне для реалізації складної розгалуженої логіки (наприклад, умов if-elif-else).
"""