import pandas as pd

# ==========================================
# ПІДГОТОВКА: Створення DataFrame (Варіант 1 — Київ)
# ==========================================
months = [
    "Січ",
    "Лют",
    "Бер",
    "Кві",
    "Тра",
    "Чер",
    "Лип",
    "Сер",
    "Вер",
    "Жов",
    "Лис",
    "Гру",
]
avg_temp = [-3.5, -2.5, 2.0, 9.0, 15.5, 19.0, 20.5, 19.5, 14.0, 8.0, 2.0, -1.5]
precip = [38, 36, 38, 41, 53, 74, 84, 69, 47, 36, 44, 44]

df = pd.DataFrame({"month": months, "avg_temp": avg_temp, "precip": precip})

print("=== БАЗОВИЙ DATAFRAME ===")
print(df.head())
print("\nФорма датафрейму:", df.shape)
print("\nТипи даних:\n", df.dtypes)
print("-" * 50)


# ==========================================
# ЗАВДАННЯ 1: Індекс
# ==========================================
print("\n=== ЗАВДАННЯ 1: Індекс ===")
print("Індекс за замовчуванням:", df.index)


df_by_month = df.set_index("month")
print("\nРядок для травня ('Тра') через .loc:")
print(df_by_month.loc["Тра"])


df = df_by_month.reset_index()
print("\nПовернений DataFrame (перші 3 рядки):")
print(df.head(3))
print("-" * 50)


# ==========================================
# ЗАВДАННЯ 2: Відбір рядків і стовпців
# ==========================================
print("\n=== ЗАВДАННЯ 2: Відбір рядків і стовпців ===")

df.index = range(1, 13)

print("1. Стовпець avg_temp для місяців із підписом від 1 до 6 через .loc:")
print(df.loc[1:6, "avg_temp"])

print("\n2. Той самий стовпець за позиціями 0–5 через .iloc:")
print(
    "(Позиції 0-5 відповідають рядкам з індексами 1-6 за рахунок фізичної нумерації пам'яті)"
)
print(df.iloc[0:6, 1])

print("\n3. Стовпці month та precip для всіх рядків:")
print(df.loc[:, ["month", "precip"]])
print("-" * 50)


# ==========================================
# ЗАВДАННЯ 3: Фільтрація за умовою
# ==========================================
print("\n=== ЗАВДАННЯ 3: Фільтрація за умовою ===")

print("1. Місяці, де avg_temp > 15:")
print(df[df["avg_temp"] > 15]["month"].values)

print("\n2. Місяці, де avg_temp > 10 і precip > 50:")
print(df[(df["avg_temp"] > 10) & (df["precip"] > 50)]["month"].values)

print("\n3. Місяці, де avg_temp < 0 або precip > 80:")
print(df[(df["avg_temp"] < 0) | (df["precip"] > 80)]["month"].values)
print("-" * 50)


# ==========================================
# ЗАВДАННЯ 4: Обчислювані стовпці
# ==========================================
print("\n=== ЗАВДАННЯ 4: Обчислювані стовпці ===")


df["avg_temp_f"] = df["avg_temp"] * 9 / 5 + 32


mean_precip = df["precip"].mean()
print(f"Середнє значення опадів по таблиці: {mean_precip:.2f} мм")
df["is_wet"] = df["precip"] > mean_precip



def get_season(row_idx):
  if row_idx in [12, 1, 2]:
    return "зима"
  elif row_idx in [3, 4, 5]:
    return "весна"
  elif row_idx in [6, 7, 8]:
    return "літо"
  else:
    return "осінь"


df["season"] = df.index.to_series().apply(get_season)

print("\nФІНАЛЬНИЙ DATAFRAME:")
print(df)


