# Питання 1: Чи можете пояснити різницю між pd.cut() і pd.qcut() — коли інтервали 
# однакової довжини, а коли гарантована однакова кількість спостережень?
#
# Відповідь:
# pd.cut() ділить діапазон значень змінної на рівні за довжиною (шириною) інтервали 
# незалежно від того, скільки елементів потрапить у кожен інтервал (розподіл спостережень 
# може бути дуже нерівномірним). 
# pd.qcut() використовує квантилі та ділить дані так, щоб у кожній створеній групі 
# була гарантовано однакова (або максимально близька) кількість спостережень, при цьому 
# довжина самих інтервалів (межі) буде різною.


# Питання 2: Чи розумієте, чому для номінальної змінної (місто) застосовують one-hot 
# кодування, а не порядкове чи просто числове (1, 2, 3)?
#
# Відповідь:
# Номінальні змінні (наприклад, назви міст) не мають природного математичного порядку 
# чи ієрархії. One-hot кодування створює окремі бінарні стовпці для кожного міста, 
# не створюючи хибних зв'язків між ними. Порядкове кодування (1, 2, 3...) впровадило б 
# штучну ранжируваність або кількісну різницю, через яку алгоритми машинного навчання 
# хибно вважали б одне місто "більшим" за інше.

