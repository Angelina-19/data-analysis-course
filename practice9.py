import pandas as pd
import numpy as np

# ==============================================================================
# ПРАКТИЧНА РОБОТА №9 — ВАРІАНТ 1 (Київ)
# ==============================================================================

BASE_PRICE = 850
BASE_QTY = 3

print("=" * 60)
print("ЗАВДАННЯ 1: Побудова набору клієнтів")
print("=" * 60)


data = {
    "вік": [22, 35, 42, 28, 51, 60, 25, 39, 45, 31],
    "дохід": [18000, 35000, 48000, 22000, 55000, 60000, 19000, 41000, 50000, 28000],
    "кількість": [3, 2, 4, 3, 5, 2, 3, 4, 3, 3],
    "місто_доставки": ["Київ", "Львів", "Одеса", "Київ", "Харків", "Львів", "Одеса", "Київ", "Харків", "Одеса"]
}

df = pd.DataFrame(data)
print(df)
print("\n")


print("=" * 60)
print("ЗАВДАННЯ 2: Похідна змінна")
print("=" * 60)


df["сума_замовлення"] = BASE_PRICE * df["кількість"]


df["частка_доходу"] = df["сума_замовлення"] / df["дохід"]

print(df[["вік", "дохід", "кількість", "сума_замовлення", "частка_доходу"]])
print("\n")


print("=" * 60)
print("ЗАВДАННЯ 3: Дискретизація")
print("=" * 60)


df["вік_група_cut"] = pd.cut(df["вік"], bins=3)
print("--- Кількість клієнтів у групах через pd.cut() ---")
print(df["вік_група_cut"].value_counts())
print()


df["вік_група_qcut"] = pd.qcut(df["вік"], q=3)
print("--- Кількість клієнтів у групах через pd.qcut() ---")
print(df["вік_група_qcut"].value_counts())
print("\n")


print("=" * 60)
print("ЗАВДАННЯ 4: Масштабування")
print("=" * 60)

c_age = df["вік"]
c_inc = df["дохід"]


df["вік_minmax"] = (c_age - c_age.min()) / (c_age.max() - c_age.min())
df["дохід_minmax"] = (c_inc - c_inc.min()) / (c_inc.max() - c_inc.min())


df["вік_z"] = (c_age - c_age.mean()) / c_age.std()
df["дохід_z"] = (c_inc - c_inc.mean()) / c_inc.std()

print(df[["вік", "вік_minmax", "вік_z", "дохід", "дохід_minmax", "дохід_z"]].head())
print("\n")


print("=" * 60)
print("ЗАВДАННЯ 5: Індикаторне кодування")
print("=" * 60)


city_dummies = pd.get_dummies(df["місто_доставки"], prefix="місто")


df_encoded = pd.concat([df, city_dummies], axis=1)

print(df_encoded[["місто_доставки"] + list(city_dummies.columns)].head(10))
print(f"\nКількість унікальних міст у даних: {df['місто_доставки'].nunique()}")
print(f"Кількість нових стовпців (dummies): {city_dummies.shape[1]}")
print("\n")


