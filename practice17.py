# КОНТРОЛЬНЕ ПИТАННЯ 1:
# Чому метод найменших квадратів мінімізує саме суму квадратів залишків, 
# а не суму самих залишків чи їхніх модулів?
# ВІДПОВІДЬ: Піднесення залишків до квадрата запобігає взаємному знищенню додатних 
# і від'ємних похибок (оскільки сума простих залишків від лінії регресії завжди дорівнює нулю). 
# Крім того, квадратична функція є гладкою (диференційовною в усіх точках, на відміну від модулів) 
# і сильніше штрафує модель за великі викиди.


# КОНТРОЛЬНЕ ПИТАННЯ 2:
# Що означає коефіцієнт нахилу b1 змістовно для вашої пари змінних, 
# і чим ця інтерпретація відрізняється від інтерпретації коефіцієнта кореляції r?
# ВІДПОВІДЬ: Нахил b1 вимірюється в конкретних одиницях вимірювання (тис. грн за 1°C) 
# і показує абсолютну швидкість зміни залежної змінної. Коефіцієнт кореляції r — 
# це безрозмірна величина від -1 до 1, що відображає лише тісноту та напрямок лінійного зв'язку, 
# але не дає відповіді на питання про масштаби зміни в одиницях виміру.


# КОНТРОЛЬНЕ ПИТАННЯ 3:
# Чому високий R² сам по собі не є достатньою підставою вважати лінійну модель адекватною — 
# що саме може показати графік залишків, чого не показує одне число R²?
# ВІДПОВІДЬ: R² показує лише частку поясненої дисперсії, але нічого не говорить про структуру помилок. 
# Графік залишків здатний виявити приховану нелінійність (дугоподібні тренди), неоднорідність 
# дисперсії помилок (гетероскедастичність) або штучні обмеження даних, які роблять лінійну модель хибною.


