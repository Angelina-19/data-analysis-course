import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.stats import linregress, pearsonr

print("=" * 60)
print(" ЕТАП 0: ПІДГОТОВКА ДАНИХ (Київ, Варіант 1)")
print("=" * 60)

np.random.seed(1)
city = "Київ"
monthly_temp = [-4, -3, 2, 9, 15, 19, 21, 20, 14, 8, 2, -2]

months = ["Січ", "Лют", "Бер", "Кві", "Тра", "Чер",
          "Лип", "Сер", "Вер", "Жов", "Лис", "Гру"]

rows = []
for month, temp in zip(months, monthly_temp):
    heating_days = np.clip(18 - temp + np.random.normal(0, 1.5), 0, 30)
    heating_days = round(heating_days)
    cost = 0.15 * heating_days + np.random.normal(0, 1.0)
    cost = round(max(cost, 0), 1)
    rows.append({
        "місто": city, "місяць": month, "температура": temp,
        "опалювальні_дні": heating_days, "витрати_на_опалення": cost,
    })

climate = pd.DataFrame(rows)
print(climate)
print("\n" + "-" * 60 + "\n")


print("=" * 60)
print(" ЗАВДАННЯ 1: Побудова регресійної моделі")
print("=" * 60)

X = climate["температура"]
Y = climate["витрати_на_опалення"]

result = linregress(X, Y)
print(f"Нахил (slope / b1)     = {result.slope:.3f}")
print(f"Перетин (intercept / b0) = {result.intercept:.3f}")
print(f"p-value                  = {result.pvalue:.3e}")

print(f"\nРівняння регресії:")
print(f"витрати_на_опалення ≈ {result.intercept:.3f} + ({result.slope:.3f}) × температура")
print("\nІнтерпретація нахилу (b1):")
print(f"Зростання середньомісячної температури на 1°C призводить до зміни витрат")
print(f"на опалення в середньому на {result.slope:.3f} тис. грн (тобто на {-result.slope*1000:.1f} грн).")
print("Знак мінус логічний: тепліше на вулиці — менше витрат на опалення.")
print("\n" + "-" * 60 + "\n")


print("=" * 60)
print(" ЗАВДАННЯ 2: Коефіцієнт детермінації R²")
print("=" * 60)


r2_method1 = result.rvalue ** 2


predicted = result.intercept + result.slope * X
residuals = Y - predicted
ss_res = np.sum(residuals ** 2)
ss_tot = np.sum((Y - np.mean(Y)) ** 2)
r2_method2 = 1 - (ss_res / ss_tot)

print(f"R² (через rvalue**2):         {r2_method1:.3f}")
print(f"R² (через суми квадратів):    {r2_method2:.3f}")


r_pearson, _ = pearsonr(X, Y)
print(f"Квадрат кореляції (r²) з Прак. 16: {r_pearson**2:.3f}")
print("\nІнтерпретація R²:")
print(f"Отримане значення R² ≈ {r2_method1:.3f} (65.0%) означає, що 65% розкиду")
print("витрат на опалення пояснюється температурою, а 35% — іншими факторами.")
print("\n" + "-" * 60 + "\n")


print("=" * 60)
print(" ЗАВДАННЯ 3: Графік залишків і оцінка адекватності")
print("=" * 60)
print("Будуємо графіки...")

fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4))


ax1.scatter(X, Y, color="blue", label="Фактичні дані")
ax1.plot(X, predicted, color="red", label="Регресійна пряма")
ax1.set_xlabel("Температура, °C")
ax1.set_ylabel("Витрати на опалення")
ax1.set_title("Регресія (Київ)")
ax1.legend()


ax2.scatter(X, residuals, color="purple")
ax2.axhline(0, color="gray", linestyle="--")
ax2.set_xlabel("Температура, °C")
ax2.set_ylabel("Залишок")
ax2.set_title("Графік залишків")

plt.tight_layout()
plt.show()

print("Аналіз графіка залишків:")
print("На теплих місяцях помітно, що залишки не зовсім випадкові — це пов'язано")
print("з обмеженням знизу в симуляції (витрати не можуть бути меншими за 0, max(cost, 0)).")
print("Це доводить, що навіть при непоганому R² лінійна модель має обмеження.")
print("\n" + "-" * 60 + "\n")


print("=" * 60)
print(" ЗАВДАННЯ 4: Прогноз і застереження щодо екстраполяції")
print("=" * 60)

temp_new = -10
predicted_cost = result.intercept + result.slope * temp_new
print(f"Прогнозовані витрати для температури -10°C: {predicted_cost:.3f} тис. грн")
print(f"Спостережений діапазон температур: від {X.min()}°C до {X.max()}°C.")
print("\nВисновок щодо екстраполяції:")
print("Температура -10°C лежить нижче за мінімальне значення вибірки (-4°C).")
print("Це екстраполяція за межі діапазону, тому надійність такого прогнозу нижча,")
print("оскільки модель не перевірена на екстремальних морозах.")
print("\n" + "-" * 60 + "\n")


print("=" * 60)
print(" ЗАВДАННЯ 5: Порівняння з коефіцієнтом кореляції")
print("=" * 60)

_, p_pearson = pearsonr(X, Y)
print(f"p-value з linregress(): {result.pvalue:.5f}")
print(f"p-value з pearsonr():   {p_pearson:.5f}")
print("\nВисновок:")
print("Обидва p-value ідентичні, оскільки нульові гіпотези про нульовий нахил")
print("регресії та нульову кореляцію для єдиного предиктора математично еквівалентні.")
print("=" * 60)


