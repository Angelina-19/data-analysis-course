import numpy as np
import pandas as pd

# ==========================================
# Варіант 1 - Київ
# Практична робота №8
# ==========================================
np.random.seed(42)              
base_temp = 9.5                  
amplitude = 14                  
city = "Київ"                    

rows = []
for year in [2021, 2022, 2023, 2024]:
    for month in range(1, 13):
        seasonal = amplitude * np.cos((month - 7) / 12 * 2 * np.pi)   
        noise = np.random.normal(0, 1.0)
        rows.append({
            "місто": city,
            "рік": year,
            "місяць": month,
            "температура": round(base_temp + seasonal + noise, 1),
        })

climate = pd.DataFrame(rows)   

print("--- 0. Початкові дані climate (перші 6 рядків) ---")
print(climate.head(6))
print("\n" + "="*60 + "\n")


print("--- ЗАВДАННЯ 1: Групування за роками та агрегація (mean, min, max) ---")
task1_result = climate.groupby("рік")["температура"].agg(["mean", "min", "max"])
print(task1_result)
print("\n[Висновок до Зв. 1]: Середньорічні температури коливаються стабільно (близько 9.7-10.0°C). Помітного тренду на потепління чи похолодання немає, коливання випадкові.\n")
print("="*60 + "\n")


print("--- ЗАВДАННЯ 2: Групування за місяцями (mean, std) ---")
task2_result = climate.groupby("місяць")["температура"].agg(["mean", "std"])
print(task2_result)
print("\n[Висновок до Зв. 2]: Найбільший стандартний розкид (std = 0.869) спостерігається у грудні (12 місяць). Перехідні сезони та початок зими зазвичай нестабільніші через погодні коливання з року в рік.\n")
print("="*60 + "\n")


print("--- ЗАВДАННЯ 3: Зведена таблиця pivot_table (місяці в рядках, роки в стовпцях) ---")
task3_result = climate.pivot_table(index="місяць", columns="рік", values="температура", aggfunc="mean")
print(task3_result)
print("\n[Висновок до Зв. 3]: Wide-формат (зведена таблиця) набагато зручніший для візуального читання людиною, тоді як довгий (tidy) формат кращий для подальшого групування та графіків.\n")
print("="*60 + "\n")



print("--- ЗАВДАННЯ 4: Похідні категорії (сезон, тепліше_за_середнє) та crosstab ---")

def get_season(month):
    if month in [12, 1, 2]:
        return "зима"
    elif month in [3, 4, 5]:
        return "весна"
    elif month in [6, 7, 8]:
        return "літо"
    else:
        return "осінь"

climate["сезон"] = climate["місяць"].apply(get_season)
climate["тепліше_за_середнє"] = climate["температура"] > base_temp

task4_result = pd.crosstab(climate["сезон"], climate["тепліше_за_середнє"])
print(task4_result)
print("\n[Висновок до Зв. 4]: Розподіл повністю логічний: усі літні місяці мають статус True (тепліші за середньорічну), а зимові — False (холодніші).\n")
print("="*60 + "\n")


print("--- ЗАВДАННЯ 5: Тестування pivot() без aggfunc ---")
task5_result = climate.pivot(index="місяць", columns="рік", values="температура")
print(task5_result.head())
print("\n[Висновок до Зв. 5]: pivot() спрацював успішно, оскільки на кожну унікальну комбінацію (місяць, рік) припадає рівно один рядок (дублікатів немає). "
      "Щоб виникла помилка (як із кав'ярнями), структуру довелося б ускладнити — наприклад, додати кілька метеостанцій на місто.\n")
print("="*60 + "\n")

