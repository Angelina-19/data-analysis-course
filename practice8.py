# 1. Чи можете пояснити словами логіку split-apply-combine, яку виконує groupby()?
# ВІДПОВІДЬ:
# - Split (Розбиття): набір даних розділяється на окремі групи на основі унікальних значень у ключовому стовпці (наприклад, "рік" чи "місяць").
# - Apply (Застосування): до кожної утвореної групи незалежно застосовується потрібна функція агрегації чи трансформації (наприклад, .agg(["mean", "min", "max"])).
# - Combine (Об'єднання): результати обчислень для всіх груп збираються назад у єдиний структурований результуючий об'єкт (DataFrame або Series).

# 2. Чи розумієте принципову відмінність між pivot() і pivot_table()?
# ВІДПОВІДЬ:
# - pivot() призначений виключно для зміни форми (reshaping) без агрегації. Якщо на одну комбінацію (індекс, стовпець) припадає кілька рядків (дублікати), Pandas не знає, яке значення обрати, і видає ValueError.
# - pivot_table() розширює pivot(), додаючи параметр агрегації (aggfunc, за замовчуванням "mean"). Це дозволяє зводити кілька значень у комірку без помилки.

# 3. Чи можете пояснити, що показує crosstab() і чим він відрізняється від groupby(...).size()?
# ВІДПОВІДЬ:
# - crosstab() (таблиця спряженості) підраховує частоти (кількість спостережень) на перетині двох чи більше категоріальних змінних, представляючи результат у зручній матричній формі.
# - На відміну від ланцюжка groupby([col1, col2]).size().unstack(), crosstab() приймає стовпці напряму як аргументи функції і є більш лаконічним інструментом для частотного аналізу.

# 4. Чому дані для groupby і pivot_table мають бути в довгому (tidy) форматі?
# ВІДПОВІДЬ:
# - У довгому форматі кожна змінна — це окремий стовпець, а кожне спостереження — рядок. Це стандарт, за якого бібліотека Pandas може легко фільтрувати рядки за категоріями та групувати дані. У широкому форматі (wide), де категорії розтягнуті в назви стовпців, інструменти групування втрачають сенс, оскільки дані сховані у заголовках.