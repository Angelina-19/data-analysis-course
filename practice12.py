import numpy as np
from scipy import stats

print("=== ВИКОНАННЯ ПРАКТИЧНОЇ РОБОТИ №12: ВАРІАНТ 1 (КИЇВ) ===")
print("=" * 60)


print("\n[ ЗАВДАННЯ 1 ] Генерація вибірки та базові показники")
np.random.seed(1)
daily_temps = np.random.normal(loc=21, scale=2.5, size=30)

print("Згенерована вибірка денних температур:")
print(np.round(daily_temps, 2))

mean_val = daily_temps.mean()
std_val = daily_temps.std(ddof=1)
n = len(daily_temps)

print(f"Вибіркове середнє (mean): {mean_val:.4f}")
print(f"Вибіркове стандартне відхилення (std з ddof=1): {std_val:.4f}")
print(f"Кількість спостережень (n): {n}")



print("\n[ ЗАВДАННЯ 2 ] Довірчий інтервал для середньої температури")
se = std_val / np.sqrt(n)
ci_mean_95 = stats.t.interval(0.95, df=n - 1, loc=mean_val, scale=se)

print(f"Стандартна похибка (se): {se:.4f}")
print(f"95% довірчий інтервал для середньої температури: {ci_mean_95}")
print("Пояснення: Використовується t-розподіл, а не z-критичне значення, оскільки справжнє стандартне відхилення генеральної сукупності (σ) невідоме, а вибірка відносно мала (n = 30).")



print("\n[ ЗАВДАННЯ 3 ] Довірчий інтервал для частки днів вище липневої норми (> 21 °C)")
p_hat = (daily_temps > 21).mean()
n_p = n * p_hat
n_1p = n * (1 - p_hat)

print(f"Частка днів (p_hat): {p_hat:.4f}")
print(f"Перевірка умови нормального наближення: n * p_hat = {n_p:.2f}, n * (1 - p_hat) = {n_1p:.2f}")
print("Обидва значення >= 5, тому умова нормального наближення виконується успішно.")

se_p = np.sqrt(p_hat * (1 - p_hat) / n)
ci_prop = stats.norm.interval(0.95, loc=p_hat, scale=se_p)
print(f"95% довірчий інтервал для частки: {ci_prop}")

in_ci = ci_prop[0] <= 0.5 <= ci_prop[1]
print(f"Чи потрапляє теоретичне значення 0.5 у побудований інтервал? {'Так' if in_ci else 'Ні'}")



print("\n[ ЗАВДАННЯ 4 ] Ширина інтервалу для середнього при рівнях довіри 90%, 95%, 99%")
levels = [0.90, 0.95, 0.99]
for level in levels:
    ci = stats.t.interval(level, df=n - 1, loc=mean_val, scale=se)
    width = ci[1] - ci[0]
    print(f"Рівень довіри {int(level*100)}%: інтервал {ci}, ширина = {width:.4f}")

print("Пояснення: Ширина зростає в міру підвищення рівня довіри (від 90% до 99%), оскільки для більшої впевненості в накритті параметра потрібен ширший діапазон. Платою за високий рівень довіри є втрата точності (збільшення ширини).")



print("\n[ ЗАВДАННЯ 5 ] Інтерпретація 95% довірчого інтервалу")
print(f"Отриманий 95% інтервал ({ci_mean_95[0]:.2f}, {ci_mean_95[1]:.2f}) означає, що при багаторазовому повторенні процедури (наприклад, побудові 100 інтервалів із нових вибірок) приблизно у 95 випадках із 100 отриманий інтервал міститиме істинне середнє значення температури. Це характеристика надійності методу, а не ймовірність для цього одного конкретного числа.")
print("=" * 60)


