# Питання 1: Яка різниця між точковою оцінкою і довірчим інтервалом — чому саме число (наприклад, x̄) недостатньо для повної відповіді?
# Відповідь: Точкова оцінка (вибіркове середнє x̄) — це лише одне число, яке через випадкову похибку вибірки майже ніколи не збігається точно з параметром генеральної сукупності. Довірчий інтервал надає діапазон правдоподібних значень разом із мірою надійності (рівнем довіри), що дозволяє оцінити точність і мінливість результату.

# Питання 2: Чому для довірчого інтервалу середнього при невідомому σ і не дуже великому n використовують t-розподіл, а не звичайний нормальний?
# Відповідь: Нормальний розподіл (z) вимагає знання справжнього стандартного відхилення генеральної сукупності (sigma).Коли ми оцінюємо його за вибіркою (s), виникає додаткова невизначеність. t-розподіл має важчі хвости, що компенсує цю похибку при малих та помірних розмірах вибірки (n).

# Питання 3: Що насправді означає "95% довіри" — сформулюйте правильно, назвавши явно, чому поширене формулювання через "ймовірність для цього інтервалу" є помилковим.
# Відповідь: "95% довіри" означає довгострокову частотну властивість методу: якщо побудувати 100 таких інтервалів з 100 незалежних вибірок, приблизно 95 з них міститимуть істинне значення параметра. Помилково говорити "з 95% ймовірністю істинне значення лежить у цьому інтервалі", оскільки істинне значення — це фіксована константа, а не випадкова величина: воно або повністю належить цьому інтервалу (1), або ні (0).

