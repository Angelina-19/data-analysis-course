print("=" * 65)
print(" ЗАВДАННЯ 0: Генерація набору даних (Варіант 1 - Київ)")
print("=" * 65)


np.random.seed(1)
city = "Київ"
base_temp = 9.5          
amplitude = 14           
base_consumption = 5200  
k = 55                  
noise_sd = 80           

months = np.arange(1, 13)
temp = base_temp + amplitude * np.cos((months - 7) / 12 * 2 * np.pi)
temp = np.round(temp + np.random.normal(0, 0.5, size=12), 1)

consumption = base_consumption - k * (temp - base_temp) + np.random.normal(0, noise_sd, size=12)
consumption = np.round(consumption, 0)

city_data = pd.DataFrame({
    "місяць": months, 
    "температура": temp, 
    "споживання_МВтгод": consumption,
})
print("Згенеровані дані спостережень:")
print(city_data)


print("\n" + "=" * 65)
print(" ЗАВДАННЯ 1: Класифікація сценарію")
print("=" * 65)
print("1. Детермінована чи стохастична? -> СТОХАСТИЧНА")
print("   (Формула лінійна, але дані містять випадковий шум noise_sd).")
print("2. Балансова, оптимізаційна, імітаційна чи жодна з них? -> ЖОДНА З ТРЬОХ")
print("   (Це класична описово-прогнозна статистична регресійна модель).")
print("3. Статична чи динамічна? -> СТАТИЧНА")
print("   (Прогноз залежить виключно від температури поточного місяця без часових лагів).")


print("\n" + "=" * 65)
print(" ЗАВДАННЯ 2: Побудова лінійної моделі")
print("=" * 65)


b, a = np.polyfit(city_data["температура"], city_data["споживання_МВтгод"], 1)
print(f"Підібрана модель: споживання ≈ {a:.1f} + ({b:.1f}) · температура")


city_data["передбачення"] = a + b * city_data["температура"]
print("\nПояснення знака b:")
print(f"Коефіцієнт b = {b:.1f} є від'ємним, що логічно: нижча температура "
      "означає більші витрати електроенергії на опалення.")


print("\n" + "=" * 65)
print(" ЗАВДАННЯ 3: Порівняння передбачень зі спостереженнями та оцінка адекватності")
print("=" * 65)


residuals = city_data["споживання_МВтгод"] - city_data["передбачення"]
city_data["залишок"] = np.round(residuals, 1)

print("Таблиця порівняння:")
print(city_data[["місяць", "температура", "споживання_МВтгод", "передбачення", "залишок"]])


ss_res = (residuals ** 2).sum()
ss_tot = ((city_data["споживання_МВтгод"] - city_data["споживання_МВтгод"].mean()) ** 2).sum()
r_squared = 1 - ss_res / ss_tot
print(f"\nКоефіцієнт детермінації R^2 = {r_squared:.4f}")
print("Висновок: високе значення R^2 свідчить про добру загальну якість підгонки, "
      "але аналіз структури залишків показує наявність систематичного зсуву.")


print("\n" + "=" * 65)
print(" ЗАВДАННЯ 4: Верифікація і валідація")
print("=" * 65)


sample_month_idx = 0
t_val = city_data.loc[sample_month_idx, "температура"]
manual_pred = a + b * t_val
code_pred = city_data.loc[sample_month_idx, "передбачення"]

print(f"Перевірка верифікації (місяць 1, температура = {t_val}°C):")
print(f" - Ручний розрахунок за формулою: {manual_pred:.1f}")
print(f" - Розрахунок у коді (передбачення): {code_pred:.1f}")
print("Висновок верифікації: Код працює коректно, значення збігаються.")
print("Валідація: Для чесної валідації недостатньо наявних 12 точок; необхідні нові незалежні дані наступного року.")


print("\n" + "=" * 65)
print(" ЗАВДАННЯ 5: Пропозиція вдосконалення моделі")
print("=" * 65)
print("Пропозиція: Додати квадратичний член (температура ** 2) або використати окремі моделі для літа і зими.")
print("Обґрунтування: Це дозволить врахувати нелінійні ефекти (наприклад, увімкнення кондиціонерів улітку), "
      "що усуне систематичні похибки в залишках.")


