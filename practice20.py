from scipy.optimize import linprog

print("=== ЗАВДАННЯ 1: Математична постановка задачі ===")
print("Виріб А (x1), Виріб Б (x2)")
print("Цільова функція: Максимізувати Z = 60*x1 + 45*x2 -> min(-60*x1 - 45*x2)")
print("Обмеження:")
print("  1) Сировина:      3*x1 + 5*x2 <= 300 (кг)")
print("  2) Робочий час:   4*x1 + 2*x2 <= 220 (год)")
print("  3) Електроенергія: 1*x1 + 1*x2 <= 95  (кВт·год)")
print("  4) Невід'ємність:  x1 >= 0, x2 >= 0\n")



print("=== ЗАВДАННЯ 2-3: Базове розв'язання та інтерпретація ===")


c = [-60, -45]


A_ub = [
    [3, 5],   
    [4, 2],   
    [1, 1],   
]
b_ub = [300, 220, 95]

bounds = [(0, None), (0, None)]


res = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method="highs")


if res.status == 0:
    print("[OK] Статус виконання: 0 (Optimization terminated successfully).")
else:
    print(f"[УВАГА] Статус виконання: {res.status}. Повідомлення: {res.message}")

opt_x1 = res.x[0]
opt_x2 = res.x[1]
max_profit = -res.fun

print(f"Оптимальний випуск: Виріб А = {opt_x1:.2f} од., Виріб Б = {opt_x2:.2f} од.")
print(f"Максимальний тижневий прибуток: {max_profit:.2f} грн\n")



print("=== ЗАВДАННЯ 4: Аналіз активних обмежень (slack) ===")
slacks = res.slack
resources = ["Сировина (кг)", "Робочий час (год)", "Електроенергія (кВт·год)"]

for i, s in enumerate(slacks):
    status_str = "АКТИВНЕ (вузьке місце, використано повністю)" if abs(s) < 1e-5 else f"НЕАКТИВНЕ (запас = {s:.2f})"
    print(f"- {resources[i]}: залишок (slack) = {s:.4f} -> {status_str}")

print("\n")



print("=== ЗАВДАННЯ 5: What-if сценарії ===")


b_ub_wi1 = [300 * 1.15, 220, 95]
res_wi1 = linprog(c, A_ub=A_ub, b_ub=b_ub_wi1, bounds=bounds, method="highs")
print(f"1) What-if (Сировина +15% до 345 кг):")
print(f"   Новий прибуток: {-res_wi1.fun:.2f} грн (зріс з {max_profit:.2f})")
print(f"   Новий випуск: А = {res_wi1.x[0]:.2f}, Б = {res_wi1.x[1]:.2f}\n")


b_ub_wi2 = [300, 220, 95 * 1.5]
res_wi2 = linprog(c, A_ub=A_ub, b_ub=b_ub_wi2, bounds=bounds, method="highs")
print(f"2) What-if (Електроенергія +50% до 142.5 кВт·год):")
print(f"   Новий прибуток: {-res_wi2.fun:.2f} грн (не змінився)")
print(f"   Новий випуск: А = {res_wi2.x[0]:.2f}, Б = {res_wi2.x[1]:.2f}\n")



