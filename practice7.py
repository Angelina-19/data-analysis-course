import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# ==========================================
# ПРАКТИЧНА РОБОТА №7
# ВАРІАНТ 1: Київ
# ==========================================

print("=== ЗАВДАННЯ 1: Генерація набору даних ===")

np.random.seed(1)
days = np.arange(1, 31)
weekend = np.isin(days % 7, [6, 0])  


temperature = np.round(np.random.normal(3, 3, size=30), 1)


base_sales = 40
random_var = np.random.normal(0, 4, size=30)
weekend_boost = np.where(weekend, base_sales * np.random.uniform(0.15, 0.25, size=30), 0)
sales = np.round(base_sales + random_var + weekend_boost).astype(int)

df = pd.DataFrame({
    "день": days,
    "вихідний": weekend,
    "температура": temperature,
    "продажі": sales
})

print("Перші 10 рядків згенерованого DataFrame:")
print(df.head(10).to_string())
print("\n")


print("=== ЗАВДАННЯ 2: Гістограма розподілу продажів ===")

fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4))

ax1.hist(df["продажі"], bins=5, edgecolor="white", color="skyblue")
ax1.set_xlabel("Кількість продажів за день (шт.)")
ax1.set_ylabel("Кількість днів")
ax1.set_title("Гістограма продажів (bins=5)")

ax2.hist(df["продажі"], bins=10, edgecolor="white", color="salmon")
ax2.set_xlabel("Кількість продажів за день (шт.)")
ax2.set_ylabel("Кількість днів")
ax2.set_title("Гістограма продажів (bins=10)")

plt.tight_layout()
plt.show()


print("=== ЗАВДАННЯ 3: Boxplot (Будні проти Вихідних) ===")
fig, ax = plt.subplots(figsize=(6, 4))
weekday_sales = df.loc[~df["вихідний"], "продажі"]
weekend_sales = df.loc[df["вихідний"], "продажі"]

ax.boxplot([weekday_sales, weekend_sales], labels=["Будні дні", "Вихідні дні"])
ax.set_ylabel("Кількість продажів (шт.)")
ax.set_title("Порівняння продажів: будні проти вихідних")
plt.show()


print("=== ЗАВДАННЯ 4: Діаграма розсіювання (Продажі проти Температури) ===")
fig, ax = plt.subplots(figsize=(6, 4))
ax.scatter(df["температура"], df["продажі"], color="purple", alpha=0.7, edgecolors="k")
ax.set_xlabel("Температура повітря (°C)")
ax.set_ylabel("Продажі (шт./день)")
ax.set_title("Залежність продажу напоїв від температури повітря")
plt.show()


print("=== ЗАВДАННЯ 5: Навмисно спотворений графік ===")
fig, (ax_correct, ax_distorted) = plt.subplots(1, 2, figsize=(14, 5))


ax_correct.hist(df["продажі"], bins=6, edgecolor="white", color="teal")
ax_correct.set_xlabel("Кількість продажів (шт.)")
ax_correct.set_ylabel("Кількість днів")
ax_correct.set_title("Коректна гістограма (з віссю від 0)")


counts, bins_edges = np.histogram(df["продажі"], bins=6)
ax_distorted.bar(bins_edges[:-1], counts, width=np.diff(bins_edges), align="edge", edgecolor="white", color="crimson")
ax_distorted.set_xlabel("Кількість продажів (шт.)")
ax_distorted.set_ylabel("Кількість днів")
ax_distorted.set_title("Спотворена гістограма (обрітана вісь Y)")
ax_distorted.set_ylim(ymin=np.min(counts) - 1)  

plt.tight_layout()
plt.show()


