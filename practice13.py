import numpy as np
from scipy import stats

print("=" * 60)
print("ПРАКТИЧНА РОБОТА №13: ПЕРЕВІРКА СТАТИСТИЧНИХ ГІПОТЕЗ")
print("Варіант 1: місто Київ | Стара норма μ0 = 20.0 °C")
print("=" * 60 + "\n")


print("--- ЗАВДАННЯ 1: Генерація вибірки та точкові оцінки ---")


np.random.seed(1)

daily_temps = np.random.normal(loc=21, scale=2.5, size=30)


x_bar = np.mean(daily_temps)
s = np.std(daily_temps, ddof=1)

print(f"Згенерована вибірка daily_temps:\n{np.round(daily_temps, 2)}")
print(f"Вибіркове середнє (x_bar): {x_bar:.4f}")
print(f"Стандартне відхилення (s): {s:.4f}\n")


print("--- ЗАВДАННЯ 2: Формулювання гіпотез та вибір тесту ---")
print("Гіпотези H0 і H1 сформульовані, обрано двобічний тест.\n")



print("--- ЗАВДАННЯ 3: Обчислення z-статистики та p-value ---")

mu0 = 20.0
n = len(daily_temps)


se = s / np.sqrt(n)


z = (x_bar - mu0) / se


p_value = 2 * (1 - stats.norm.cdf(abs(z)))

print(f"Стандартна похибка (se) = {se:.4f}")
print(f"z-статистика (z) = {z:.3f}")
print(f"p-value = {p_value:.4f}\n")



print("--- ЗАВДАННЯ 4: Прийняття рішення та висновок ---")

alpha = 0.05
if p_value < alpha:
    decision = "Відхиляємо H0"
else:
    decision = "Не відхиляємо H0"

print(f"Рішення при alpha = {alpha}: {decision}")


conclusion = (
    f"Висновок словами: Наявні дані для міста Київ не дають достатніх статистичних підстав "
    f"відхилити стару норму середньої липневої температури 20.0 °C на рівні значущості alpha = 0.05 "
    f"(p ≈ {p_value:.3f}, двобічний тест)."
)
print(conclusion + "\n")



print("--- ЗАВДАННЯ 5: Довірчий інтервал та аналіз помилок ---")


ci_lower = x_bar - 1.96 * se
ci_upper = x_bar + 1.96 * se

print(f"95% довірчий інтервал для середньої температури: [{ci_lower:.4f}, {ci_upper:.4f}]")
is_mu0_in = ci_lower <= mu0 <= ci_upper
print(f"Чи потрапляє μ0 = {mu0} всередину інтервалу? {'Так' if is_mu0_in else 'Ні'}")
print("Це повністю узгоджується з рішенням у Завданні 4 не відхиляти H0.\n")


