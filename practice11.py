import numpy as np
import matplotlib.pyplot as plt

# ==============================================================================
# Практична робота №11 Варіант - 1 (Київ)
# ==============================================================================

rng = np.random.default_rng(1)

lam = 0.20
true_mean = 1 / lam  # 5.0 хвилин (теоретичне математичне сподівання)
n_repeats = 10_000

print("=== ВАРІАНТ 1: м. Київ, λ = 0.20, Теоретичне середнє E[X] = 5.0 хв ===\n")

# ==============================================================================
# ЗАВДАННЯ 1. Перевірка закону великих чисел 
# ==============================================================================
print("--- ЗАВДАННЯ 1: Закон великих чисел ---")
for n in [5, 50, 500, 20_000]:
    sample = rng.exponential(scale=true_mean, size=n)
    sample_mean = sample.mean()
    abs_diff = abs(sample_mean - true_mean)
    print(f"n = {n:6d} | Вибіркове середнє: {sample_mean:.4f} | Абсолютна різниця: {abs_diff:.4f}")

# ==============================================================================
# ЗАВДАННЯ 2. Вибірковий розподіл середнього для двох n 
# ==============================================================================
print("\n--- ЗАВДАННЯ 2: Вибірковий розподіл середнього (будуються графіки) ---")
n_small = 10
n_large = 300


means_n10 = rng.exponential(scale=true_mean, size=(n_repeats, n_small)).mean(axis=1)
means_n300 = rng.exponential(scale=true_mean, size=(n_repeats, n_large)).mean(axis=1)

print(f"Для n={n_small}: середнє вибіркових середніх = {means_n10.mean():.4f}, std = {means_n10.std():.4f}")
print(f"Для n={n_large}: середнє вибіркових середніх = {means_n300.mean():.4f}, std = {means_n300.std():.4f}")


fig, axes = plt.subplots(1, 2, figsize=(11, 4))
axes[0].hist(means_n10, bins=40, density=True, color='skyblue', edgecolor='black')
axes[0].set_title(f"n = {n_small} (Скошена форма)\nstd = {means_n10.std():.3f}")
axes[0].set_xlabel("Вибіркове середнє")
axes[0].set_ylabel("Густина")

axes[1].hist(means_n300, bins=40, density=True, color='salmon', edgecolor='black')
axes[1].set_title(f"n = {n_large} (Дзвоноподібна форма)\nstd = {means_n300.std():.3f}")
axes[1].set_xlabel("Вибіркове середнє")
plt.suptitle("Завдання 2: Перехід до нормального розподілу (ЦГТ)")
plt.tight_layout()
plt.show()

# ==============================================================================
# ЗАВДАННЯ 3. Стандартна похибка: теорія проти симуляції
# ==============================================================================
print("\n--- ЗАВДАННЯ 3: Стандартна похибка (Теорія vs Симуляція) ---")
print(f"{'n':<6} | {'Теоретична SE':<15} | {'Виміряна std':<15} | {'Різниця':<10}")
print("-" * 52)

n_list = [10, 30, 100, 300]
for n in n_list:
    se_theo = true_mean / np.sqrt(n)
    sim_means = rng.exponential(scale=true_mean, size=(n_repeats, n)).mean(axis=1)
    se_sim = sim_means.std()
    diff = abs(se_theo - se_sim)
    print(f"{n:<6d} | {se_theo:<15.4f} | {se_sim:<15.4f} | {diff:<10.4f}")

# ==============================================================================
# ЗАВДАННЯ 4. Закон убуваючої віддачі
# ==============================================================================
print("\n--- ЗАВДАННЯ 4: Закон убуваючої віддачі ---")
n1 = 25
n2 = 100
se_25 = true_mean / np.sqrt(n1)
se_100 = true_mean / np.sqrt(n2)
ratio_se = se_25 / se_100
ratio_n = n2 / n1

print(f"SE для n = {n1}: {se_25:.4f}")
print(f"SE для n = {n2}: {se_100:.4f}")
print(f"Висновок: Збільшення n у {ratio_n} рази зменшило SE рівно у {ratio_se:.2f} рази (тобто увімкнено квадратний корінь).")

# ==============================================================================
# ЗАВДАННЯ 5. Вплив величини n_repeats на якість симуляції 
# ==============================================================================
print("\n--- ЗАВДАННЯ 5: Вплив n_repeats на якість симуляції (будується графік) ---")
n_repeats_small = 50
means_n10_few = rng.exponential(scale=true_mean, size=(n_repeats_small, 10)).mean(axis=1)

plt.figure(figsize=(5, 3.5))
plt.hist(means_n10_few, bins=15, density=True, color='lightgreen', edgecolor='black')
plt.title(f"n_repeats = {n_repeats_small} (при n=10)")
plt.xlabel("Вибіркове середнє")
plt.ylabel("Густина")
plt.suptitle("Завдання 5 (Додатково): Мала кількість повторів")
plt.tight_layout()
plt.show()



